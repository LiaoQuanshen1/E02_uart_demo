#ifndef _my_image_show_h_
#define _my_image_show_h_

#include "zf_common_headfile.h"

/* ==================== 图像显示布局配置 ==================== */
#define IMAGE_DISPLAY_BOTTOM_Y  200     /* 图像区域底部 Y 坐标，底部留给菜单   */
#define IMAGE_ORIGINAL_H        MT9V03X_H  /* 原始图显示高度（上半屏 120 行） */

/* 二值化图像显示高度 = 底部边界 - 原始图高度 */
#define IMAGE_BINARY_H          (IMAGE_DISPLAY_BOTTOM_Y - IMAGE_ORIGINAL_H)

//-------------------------------------------------------------------------------------------------------------------
// 巡线结果数组 — 供控制算法引用
// 注意：仅在 image_show() 调用后更新，edge_valid 为 0 的行数据无效
//-------------------------------------------------------------------------------------------------------------------
extern uint16 left_edge[MT9V03X_H];                                            // 每行左边界 x 坐标，无效时为 0xFFFF
extern uint16 right_edge[MT9V03X_H];                                           // 每行右边界 x 坐标，无效时为 0xFFFF
extern uint16 center_line[MT9V03X_H];                                          // 每行中线   x 坐标
extern uint8  edge_valid[MT9V03X_H];                                           // 每行巡线数据是否有效

//-------------------------------------------------------------------------------------------------------------------
// 图像采集 + 大津法二值化 + IPS200 显示 + 巡线绘制
// 应在主循环中每帧调用一次
//-------------------------------------------------------------------------------------------------------------------
extern void image_show (void);

#endif
